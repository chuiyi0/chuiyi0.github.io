const assert=require('node:assert/strict');
const {boot,catalog}=require('./verify048.cjs');
const first=catalog.entries[0],family=catalog.families.find(f=>f.id===first.family_id);
const removed=Object.fromEntries(family.entry_ids.map(id=>[id,true]));
const editor=boot(true,{bookMeta:{name:'test book',families:{[family.id]:{story:'family story'}},stories:[{id:'story-keep',title:'keep story',text:'unchanged',entry_ids:[first.id,catalog.entries.find(w=>w.family_id!==family.id).id]}]}});
editor.closeMenu=()=>{};editor.phrasesPage=()=>'';
editor.CYTheme={get:()=> 'paper',compactPreview:()=>'',apply:()=>{}};
const t=editor.TEST;t.setRoute({name:'word',id:first.id});
assert(t.header().includes('data-action="delete-book-word"'));
assert.equal(t.deleteBookWord(first.id),true);
assert.equal(editor.CY_CATALOG.entries.length,catalog.entries.length,'confirmation must happen first');
t.confirm();
assert(!editor.CY_CATALOG.entries.some(w=>w.id===first.id));
assert(!editor.CY_CATALOG.families.some(f=>f.entry_ids.includes(first.id)));
assert(!t.studyWords().includes(first.id));
assert(t.readState().deletedWords[first.id]);
editor.CYBook.savePending=()=>{};t.capture();t.exportBook048();const exported=JSON.parse(editor.output.text);
assert(!exported.catalog.entries.some(w=>w.id===first.id));
assert(!exported.shared.bookMeta.stories[0].entry_ids.includes(first.id));
assert.equal(exported.shared.bookMeta.stories[0].text,'unchanged');
assert(t.validateBook048(exported));
const restarted=boot(true,JSON.parse(JSON.stringify(t.readState())));
assert(!restarted.CY_CATALOG.entries.some(w=>w.id===first.id)),'restart must not restore deleted words';
const publicApp=boot(false,JSON.parse(JSON.stringify(t.readState())));
publicApp.CYTheme={get:()=> 'paper',compactPreview:()=>'',apply:()=>{}};
publicApp.TEST.setRoute({name:'word',id:first.id});
assert(!publicApp.TEST.header().includes('delete-book-word'));
assert.equal(publicApp.TEST.deleteBookWord(first.id),false);
assert.equal(publicApp.CY_CATALOG.entries.length,catalog.entries.length,'editor deletion must not change public book');
const cleaned=t.pruneBookWords(catalog,{words:{[first.id]:{note:'remove'}},bookMeta:{families:{[family.id]:{}},stories:[{id:'story-keep',entry_ids:family.entry_ids}]}},removed);
assert(!cleaned.catalog.families.some(f=>f.id===family.id));
assert(!cleaned.shared.words[first.id]);assert.deepEqual(cleaned.shared.bookMeta.stories[0].entry_ids,[]);
const all=Object.fromEntries(catalog.entries.map(w=>[w.id,true]));
const empty=t.pruneBookWords(catalog,{words:{}},all);
assert.equal(empty.catalog.entries.length,0);assert.equal(empty.catalog.families.length,0);
assert(t.validateBook048({format:'chuiyi-wordbook',version:1,catalog:empty.catalog,shared:empty.shared}));
console.log('PASS editor-only word deletion: confirmation, restart, export, relations, empty book and public isolation');
