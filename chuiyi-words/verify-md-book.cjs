const fs=require('node:fs'),assert=require('node:assert/strict');
const md=require('./app/md-book.js');
const catalog=require('./app/catalog.json'),shared=require('./app/shared.json'),layout=require('./app/wordbook-layout.json');
const {compile}=require('./compile-wordbook.cjs');
const source=fs.readFileSync(__dirname+'/app/wordbook.md','utf8');
const parsed=md.splitBook(source,layout),view=compile(__dirname+'/app/wordbook.md');
const byId=new Map(catalog.entries.map(w=>[w.id,w]));
const current=id=>({...byId.get(id),...shared.words[id],...view.edits[id]});
assert.equal(parsed.entries.length,7375);
assert.equal(parsed.groups.length,2068);
assert.equal(new Set(catalog.families.map(f=>f.id)).size,5032);
assert.deepEqual(md.verifyBook(parsed,catalog,layout).errors,[]);
assert(parsed.entries.every(w=>w.id===byId.get(w.id).id&&w.word===byId.get(w.id).word&&w.groupId===layout.words[w.id]));
assert(!/<!-- id:|^故事[：:]/m.test(source));
assert.equal(parsed.extraPhrases.length,63);
assert.deepEqual(parsed.extraPhrases,catalog.extraPhrases);
assert.equal(parsed.entries.reduce((n,w)=>n+w.collocations.length,0),24922);
assert.equal(new Set(parsed.entries.flatMap(w=>w.collocations).concat(parsed.extraPhrases).map(row=>row[0])).size,23976);
assert.deepEqual(parsed.entries.map(w=>w.collocations),parsed.entries.map(w=>current(w.id).collocations));
assert(parsed.entries.every(w=>w.ipa===current(w.id).ipa_us));
assert(parsed.entries.every(w=>w.meaningRaw===md.formatMeanings(current(w.id).meanings)));
assert(!Object.values(view.edits).some(p=>p.meanings),'visual POS grouping must not modify primary meanings or sense groups');
assert.equal(md.composeBook(parsed,current,parsed.extraPhrases),source,'canonical round trip');
const january=parsed.entries.find(w=>w.word==='January');
const february=parsed.entries.find(w=>w.word==='February');
const march=parsed.entries.find(w=>w.word==='March');
const reordered=[...parsed.lines.slice(0,january.start),...parsed.lines.slice(february.start,march.start),...parsed.lines.slice(january.start,february.start),...parsed.lines.slice(march.start)].join('\n');
const moved=md.splitBook(reordered,layout);
assert(md.verifyBook(moved,catalog,layout).ok);
assert.deepEqual(moved.entries.slice(0,3).map(w=>w.id),[february.id,january.id,march.id]);
assert.notEqual(march.id,parsed.entries.find(w=>w.word==='march').id);
const renamed=md.splitBook(source.replace('#### January\n','#### JanuarY\n'),layout);
assert(!md.verifyBook(renamed,catalog,layout).ok);
assert(md.verifyBook(renamed,catalog,layout,current,new Map([['JanuarY',january.id]])).ok);
assert.equal(md.compareBook(renamed,catalog,current).find(c=>c.id===january.id).patch.word,'JanuarY');
const marchChanged=md.splitBook(source.replace('#### March\n','#### February\n'),layout);
assert(!md.verifyBook(marchChanged,catalog,layout).ok);
const sample=md.phraseIndex([{id:'A',collocations:[['Same phrase','翻译一']]},{id:'B',collocations:[['same  phrase','翻译二'],['same phrase.','含句号']]}],[]);
assert.deepEqual(sample.get('same phrase').map(x=>[x.id,x.row[1]]),[['A','翻译一'],['B','翻译二']]);
assert.equal(sample.get('same phrase.').length,1);
assert.equal(md.removedPhrases([['x','译'],['x','译']],[['x','译']]).length,1);
console.log('PASS: 7,375 stable words, 2,068 Markdown groups, 5,032 catalog families, 24,922 linked phrase occurrences, 23,976 distinct expressions, 63 standalone expressions, exact MD round trip, reorder and rename confirmation');
